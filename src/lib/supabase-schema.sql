-- 1. Cria a tabela de Ordens de Serviço
CREATE TABLE IF NOT EXISTS public.orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  os_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  client_name TEXT NOT NULL,
  client_phone TEXT NOT NULL,
  device_type TEXT NOT NULL CHECK (device_type IN ('celular', 'videogame', 'outro')),
  device_brand TEXT NOT NULL,
  device_model TEXT NOT NULL,
  defect_reported TEXT NOT NULL,
  technical_report TEXT,
  status TEXT NOT NULL DEFAULT 'aguardando_orcamento' CHECK (
    status IN ('aguardando_orcamento', 'aprovado', 'em_bancada', 'aguardando_peca', 'pronto', 'entregue', 'cancelado')
  ),
  technician_name TEXT NOT NULL,
  cost_parts NUMERIC(10,2) DEFAULT 0.00,
  total_price NUMERIC(10,2) DEFAULT 0.00,
  accessories TEXT,
  device_password TEXT,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 2. Habilita Row Level Security (RLS) e libera acesso com a Anon Key
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Acesso livre bancada para ordens" ON public.orders;
CREATE POLICY "Acesso livre bancada para ordens" 
  ON public.orders 
  FOR ALL 
  USING (true) 
  WITH CHECK (true);

-- 3. Habilita Realtime para que você e seu colega vejam mudanças no celular ao mesmo tempo
ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;

